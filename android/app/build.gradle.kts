// ---- Rust core: op-ffi built with cargo-ndk, Kotlin bindings generated by UniFFI ----

val workspaceRoot: File = rootDir.parentFile
val cargoBin: Provider<String> = providers.environmentVariable("CARGO")
    .orElse("${System.getProperty("user.home")}/.cargo/bin/cargo")
val rustAbis: Provider<List<String>> = providers.gradleProperty("rustAbis").map { it.split(",").map(String::trim) }

abstract class CargoNdkBuild : DefaultTask() {
    @get:InputFiles @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val rustSources: ConfigurableFileCollection
    @get:Input abstract val abis: ListProperty<String>
    @get:Input abstract val cargo: Property<String>
    @get:Internal abstract val cargoHome: Property<String>
    @get:Internal abstract val workspace: DirectoryProperty
    @get:Internal abstract val ndkDir: DirectoryProperty
    @get:OutputDirectory abstract val outputDir: DirectoryProperty
    @get:Inject abstract val execOps: ExecOperations

    @TaskAction
    fun build() {
        val out = outputDir.get().asFile.apply { deleteRecursively(); mkdirs() }
        execOps.exec {
            workingDir = workspace.get().asFile
            environment("ANDROID_NDK_HOME", ndkDir.get().asFile.absolutePath)
            // Reproducible, private builds: dependency sources live under the builder's home
            // (~/.cargo/registry/...), and those paths end up in panic messages. Remap them to a
            // fixed prefix so the library is the same on any machine and leaks no username.
            // RUSTFLAGS replaces .cargo/config.toml, so hardware AES (see there) is set here too;
            // the cfg only has an effect on aarch64.
            environment(
                "CARGO_ENCODED_RUSTFLAGS",
                listOf("--remap-path-prefix=${cargoHome.get()}=/cargo", "--cfg", "aes_armv8").joinToString("\u001f"),
            )
            // Always release: Argon2id is unusably slow unoptimized.
            commandLine(
                listOf(cargo.get(), "ndk") + abis.get().flatMap { listOf("-t", it) } +
                    listOf("-P", "28", "-o", out.absolutePath, "build", "--release", "--locked", "-p", "op-ffi"),
            )
        }
    }
}

abstract class UniffiBindgen : DefaultTask() {
    @get:InputFiles @get:PathSensitive(PathSensitivity.NONE)
    abstract val library: ConfigurableFileCollection
    @get:Input abstract val cargo: Property<String>
    @get:Internal abstract val workspace: DirectoryProperty
    @get:OutputDirectory abstract val outputDir: DirectoryProperty
    @get:Inject abstract val execOps: ExecOperations

    @TaskAction
    fun generate() {
        val out = outputDir.get().asFile.apply { deleteRecursively(); mkdirs() }
        execOps.exec {
            workingDir = workspace.get().asFile
            commandLine(
                cargo.get(), "run", "-q", "--locked", "-p", "op-ffi", "--features", "bindgen", "--bin", "uniffi-bindgen", "--",
                "generate", "--library", library.singleFile.absolutePath, "--language", "kotlin", "--no-format",
                "--out-dir", out.absolutePath,
            )
        }
    }
}

/** Fails the build if the merged manifest could reach the network or be backed up. */
abstract class VerifyManifest : DefaultTask() {
    @get:InputFile @get:PathSensitive(PathSensitivity.NONE)
    abstract val manifest: RegularFileProperty

    @TaskAction
    fun verify() {
        val text = manifest.get().asFile.readText()
        val forbidden = listOf("android.permission.INTERNET", "android.permission.ACCESS_NETWORK_STATE")
            .filter { text.contains("\"$it\"") }
        if (forbidden.isNotEmpty()) throw GradleException("The manifest declares forbidden permissions: $forbidden")
        val required = listOf("android.permission.HIDE_OVERLAY_WINDOWS")
            .filterNot { text.contains("\"$it\"") }
        if (required.isNotEmpty()) throw GradleException("The manifest must declare the protection permissions: $required")
        if (text.contains("\"android.permission.QUERY_ALL_PACKAGES\"")) throw GradleException("QUERY_ALL_PACKAGES is forbidden: use <queries> with concrete packages")
        if (!text.contains("android:allowBackup=\"false\"")) throw GradleException("android:allowBackup must be false")
    }
}

val cargoBuild = tasks.register<CargoNdkBuild>("cargoBuild") {
    rustSources.from(
        fileTree(workspaceRoot) {
            include("Cargo.toml", "Cargo.lock", "core/Cargo.toml", "core/src/**", "ffi/Cargo.toml", "ffi/uniffi.toml", "ffi/src/**")
        },
    )
    abis.set(rustAbis)
    cargo.set(cargoBin)
    cargoHome.set(providers.environmentVariable("CARGO_HOME").orElse("${System.getProperty("user.home")}/.cargo"))
    workspace.set(workspaceRoot)
    ndkDir.set(androidComponents.sdkComponents.ndkDirectory)
    outputDir.set(layout.buildDirectory.dir("rust/jniLibs"))
}

val uniffiBindings = tasks.register<UniffiBindgen>("uniffiBindings") {
    library.from(cargoBuild.flatMap { it.outputDir.file(rustAbis.get().first() + "/libop_ffi.so") })
    cargo.set(cargoBin)
    workspace.set(workspaceRoot)
    outputDir.set(layout.buildDirectory.dir("generated/uniffi"))
}

androidComponents.onVariants { variant ->
    variant.sources.jniLibs?.addGeneratedSourceDirectory(cargoBuild, CargoNdkBuild::outputDir)
    variant.sources.kotlin?.addGeneratedSourceDirectory(uniffiBindings, UniffiBindgen::outputDir)

    val verify = tasks.register<VerifyManifest>("verify${variant.name.replaceFirstChar(Char::uppercase)}Manifest") {
        manifest.set(variant.artifacts.get(SingleArtifact.MERGED_MANIFEST))
    }
    tasks.matching { it.name == "assemble${variant.name.replaceFirstChar(Char::uppercase)}" }
        .configureEach { dependsOn(verify) }
}

