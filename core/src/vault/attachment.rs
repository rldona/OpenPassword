//! Encrypted images attached to an item.
//!
//! Each image is sealed with the item key under its own AAD, so it can only be opened as part
//! of that item in that vault. The attachment is immutable: replacing an image creates a new
//! id, which is why the item revision is not part of the AAD.

use serde::{Deserialize, Serialize};
use zeroize::Zeroizing;

use super::padding;
use super::{ItemId, VaultId};
use crate::crypto::{self, DOMAIN_ATTACHMENT, Key, NONCE_LEN, TAG_LEN, aad, random_array};
use crate::encoding::{base64_bytes, hex_bytes};
use crate::{Error, Result};

pub type AttachmentId = [u8; 16];

/// 1.5 MiB. Below Android's 2 MB `CursorWindow` limit per row: bigger rows cannot be read.
pub const MAX_IMAGE_BYTES: usize = 1_572_864;
/// Images per item. Enough for a multi-page policy.
pub const MAX_IMAGES_PER_ITEM: usize = 10;
/// Sum of sealed attachment bytes in a vault. Keeps a backup well under 64 MiB in base64.
pub const MAX_VAULT_ATTACHMENT_BYTES: u64 = 24 * 1024 * 1024;
/// Images are large: 4 KiB blocks keep the size leak coarse without inflating small ones.
pub(crate) const ATTACHMENT_PAD_BLOCK: usize = 4096;
/// Largest sealed attachment we will try to open, checked before touching the cipher.
pub const MAX_SEALED_ATTACHMENT_LEN: usize = NONCE_LEN
    + TAG_LEN
    + (4 + 2 + MAX_IMAGE_BYTES).div_ceil(ATTACHMENT_PAD_BLOCK) * ATTACHMENT_PAD_BLOCK;

const ATTACHMENT_VERSION: u8 = 1;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum MediaType {
    Jpeg,
}

impl MediaType {
    fn to_byte(self) -> u8 {
        match self {
            MediaType::Jpeg => 1,
        }
    }

    fn from_byte(byte: u8) -> Result<Self> {
        match byte {
            1 => Ok(MediaType::Jpeg),
            _ => Err(Error::Malformed("unknown media type")),
        }
    }
}

/// A new image to seal. The id is generated by [`new_attachment_id`].
pub struct NewImage {
    pub id: AttachmentId,
    pub jpeg: Zeroizing<Vec<u8>>,
}

impl core::fmt::Debug for NewImage {
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        f.write_str("NewImage(<redacted>)")
    }
}

/// A decrypted image.
pub struct Image {
    pub media_type: MediaType,
    pub jpeg: Zeroizing<Vec<u8>>,
}

impl core::fmt::Debug for Image {
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        f.write_str("Image(<redacted>)")
    }
}

/// An item and its decrypted images, to move them to another vault. Never crosses the FFI.
pub struct PlainItem {
    pub item: super::Item,
    pub images: Vec<(AttachmentId, Image)>,
}

impl core::fmt::Debug for PlainItem {
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        f.write_str("PlainItem(<redacted>)")
    }
}

/// A sealed attachment as stored on disk and in backups.
#[derive(Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct EncryptedAttachment {
    #[serde(with = "hex_bytes")]
    pub item_id: ItemId,
    #[serde(with = "hex_bytes")]
    pub id: AttachmentId,
    #[serde(with = "base64_bytes")]
    pub data: Vec<u8>,
}

impl core::fmt::Debug for EncryptedAttachment {
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        f.debug_struct("EncryptedAttachment")
            .field("item_id", &hex::encode(self.item_id))
            .field("id", &hex::encode(self.id))
            .field("data_len", &self.data.len())
            .finish()
    }
}

/// What a save writes: the item plus the attachments to add and remove, atomically.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ItemChange {
    pub item: super::EncryptedItem,
    pub added: Vec<EncryptedAttachment>,
    pub removed: Vec<AttachmentId>,
}

pub fn new_attachment_id() -> Result<AttachmentId> {
    random_array::<16>()
}

/// Parses an image field value: canonical lowercase hex of 16 bytes.
pub(crate) fn parse_id(value: &str) -> Result<AttachmentId> {
    let bytes = hex::decode(value).map_err(|_| Error::InvalidInput("invalid image id"))?;
    let id: AttachmentId = bytes
        .try_into()
        .map_err(|_| Error::InvalidInput("invalid image id"))?;
    if hex::encode(id) != value {
        return Err(Error::InvalidInput("invalid image id"));
    }
    Ok(id)
}

fn attachment_aad(vault_id: &VaultId, item_id: &ItemId, id: &AttachmentId) -> Vec<u8> {
    aad(DOMAIN_ATTACHMENT, &[b"image", vault_id, item_id, id])
}

pub(crate) fn seal(
    vault_id: &VaultId,
    item_id: &ItemId,
    key: &Key,
    image: &NewImage,
) -> Result<EncryptedAttachment> {
    check_jpeg(&image.jpeg)?;
    seal_bytes(
        vault_id,
        item_id,
        key,
        image.id,
        &Image {
            media_type: MediaType::Jpeg,
            jpeg: Zeroizing::new(image.jpeg.to_vec()),
        },
    )
}

pub(crate) fn seal_bytes(
    vault_id: &VaultId,
    item_id: &ItemId,
    key: &Key,
    id: AttachmentId,
    image: &Image,
) -> Result<EncryptedAttachment> {
    let mut plain = Zeroizing::new(Vec::with_capacity(2 + image.jpeg.len()));
    plain.push(ATTACHMENT_VERSION);
    plain.push(image.media_type.to_byte());
    plain.extend_from_slice(&image.jpeg);
    let padded = padding::pad_to(&plain, ATTACHMENT_PAD_BLOCK)?;
    let data = crypto::seal(key, &padded, &attachment_aad(vault_id, item_id, &id))?;
    Ok(EncryptedAttachment {
        item_id: *item_id,
        id,
        data,
    })
}

pub(crate) fn open(
    vault_id: &VaultId,
    item_id: &ItemId,
    key: &Key,
    attachment: &EncryptedAttachment,
) -> Result<Image> {
    if attachment.item_id != *item_id {
        return Err(Error::InvalidInput("attachment does not belong to item"));
    }
    if attachment.data.len() > MAX_SEALED_ATTACHMENT_LEN {
        return Err(Error::Malformed("attachment too large"));
    }
    let padded = crypto::open(
        key,
        &attachment.data,
        &attachment_aad(vault_id, item_id, &attachment.id),
    )?;
    let plain = padding::unpad_from(&padded, ATTACHMENT_PAD_BLOCK)?;
    if plain.len() < 2 || plain[0] != ATTACHMENT_VERSION {
        return Err(Error::Malformed("attachment header"));
    }
    let media_type = MediaType::from_byte(plain[1])?;
    let jpeg = &plain[2..];
    if jpeg.len() > MAX_IMAGE_BYTES {
        return Err(Error::Malformed("attachment too large"));
    }
    Ok(Image {
        media_type,
        jpeg: Zeroizing::new(jpeg.to_vec()),
    })
}

/// Accepts only a re-encoded JPEG with no metadata: SOI, then the segments a plain encoder
/// emits, then SOS, and EOI at the very end.
///
/// Rejects APP1 (Exif or XMP), COM and MPF, so GPS and camera data cannot reach the vault.
pub(crate) fn check_jpeg(data: &[u8]) -> Result<()> {
    if data.len() > MAX_IMAGE_BYTES {
        return Err(Error::InvalidInput("image too large"));
    }
    if data.len() < 4 || !data.starts_with(&[0xFF, 0xD8]) || !data.ends_with(&[0xFF, 0xD9]) {
        return Err(Error::InvalidInput("not a JPEG"));
    }
    let mut i = 2;
    loop {
        if i >= data.len() || data[i] != 0xFF {
            return Err(Error::InvalidInput("not a JPEG"));
        }
        while i < data.len() && data[i] == 0xFF {
            i += 1;
        }
        if i >= data.len() {
            return Err(Error::InvalidInput("not a JPEG"));
        }
        let marker = data[i];
        i += 1;
        if marker == 0xDA {
            // Start of scan: the entropy-coded data runs to the EOI checked above.
            return Ok(());
        }
        if marker == 0xD9 {
            return Ok(());
        }
        if !matches!(marker, 0xE0 | 0xE2 | 0xDB | 0xC4 | 0xC0 | 0xC2 | 0xDD) {
            return Err(Error::InvalidInput("image has metadata"));
        }
        if i + 2 > data.len() {
            return Err(Error::InvalidInput("not a JPEG"));
        }
        let len = u16::from_be_bytes([data[i], data[i + 1]]) as usize;
        if len < 2 || i + len > data.len() {
            return Err(Error::InvalidInput("not a JPEG"));
        }
        if marker == 0xE2 {
            let content = &data[i + 2..i + len];
            if !content.starts_with(b"ICC_PROFILE\0") {
                return Err(Error::InvalidInput("image has metadata"));
            }
        }
        i += len;
    }
}

#[cfg(fuzzing)]
pub mod fuzzing {
    /// Runs the JPEG validator on arbitrary bytes.
    pub fn check_jpeg(data: &[u8]) -> bool {
        super::check_jpeg(data).is_ok()
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn jpeg() -> Vec<u8> {
        // Minimal structurally valid JPEG: SOI, DQT, SOF0, DHT, SOS, EOI.
        let segment = |marker: u8, payload: &[u8]| {
            let mut out = vec![0xFF, marker];
            out.extend_from_slice(&u16::try_from(payload.len() + 2).unwrap().to_be_bytes());
            out.extend_from_slice(payload);
            out
        };
        let mut out = vec![0xFF, 0xD8];
        out.extend(segment(0xDB, &[0; 65]));
        out.extend(segment(0xC0, &[8, 0, 1, 0, 1, 1, 1, 0x11, 0]));
        out.extend(segment(0xC4, &[0; 20]));
        out.extend(segment(0xDA, &[1, 1, 0, 0, 63, 0]));
        out.extend_from_slice(&[0x12, 0x34]);
        out.extend_from_slice(&[0xFF, 0xD9]);
        out
    }

    #[test]
    fn accepts_a_plain_jpeg() {
        check_jpeg(&jpeg()).unwrap();
    }

    #[test]
    fn rejects_trailing_data_and_metadata() {
        let mut with_app1 = vec![0xFF, 0xD8, 0xFF, 0xE1, 0x00, 0x08];
        with_app1.extend_from_slice(b"Exif\0\0");
        with_app1.extend_from_slice(&jpeg()[2..]);
        assert_eq!(
            check_jpeg(&with_app1).unwrap_err(),
            Error::InvalidInput("image has metadata")
        );
        let mut trailing = jpeg();
        trailing.extend_from_slice(b"x");
        assert_eq!(
            check_jpeg(&trailing).unwrap_err(),
            Error::InvalidInput("not a JPEG")
        );
        let mut png = vec![0x89, b'P', b'N', b'G'];
        png.extend_from_slice(&[0; 8]);
        assert_eq!(
            check_jpeg(&png).unwrap_err(),
            Error::InvalidInput("not a JPEG")
        );
    }

    #[test]
    fn accepts_an_icc_profile_but_not_other_app2() {
        let mut with_icc = vec![0xFF, 0xD8, 0xFF, 0xE2];
        let payload = b"ICC_PROFILE\0\x01\x01profile";
        with_icc.extend_from_slice(&u16::try_from(payload.len() + 2).unwrap().to_be_bytes());
        with_icc.extend_from_slice(payload);
        with_icc.extend_from_slice(&jpeg()[2..]);
        check_jpeg(&with_icc).unwrap();

        let mut with_mpf = vec![0xFF, 0xD8, 0xFF, 0xE2, 0x00, 0x06, b'M', b'P', b'F', 0];
        with_mpf.extend_from_slice(&jpeg()[2..]);
        assert_eq!(
            check_jpeg(&with_mpf).unwrap_err(),
            Error::InvalidInput("image has metadata")
        );
    }

    #[test]
    fn rejects_oversized_and_truncated() {
        assert_eq!(
            check_jpeg(&vec![0xFF; MAX_IMAGE_BYTES + 1]).unwrap_err(),
            Error::InvalidInput("image too large")
        );
        assert_eq!(
            check_jpeg(&jpeg()[..jpeg().len() - 1]).unwrap_err(),
            Error::InvalidInput("not a JPEG")
        );
    }
}
